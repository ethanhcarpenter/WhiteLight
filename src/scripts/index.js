const audio = new Audio();
let selectedKey = null;
let slotData = [];
let isPlaying = false;

audio.volume = 0.3; 

function getAudio(){
    return audio;
}

function getAlbums() {
    return albums;
}

function getSelectedKey() {
    return selectedKey;
}
function setSelectedKey(key) {
    selectedKey = key;
}

function getSlotData() {
    return slotData;
}
function pushSlotData(data) {
    slotData.push(data);
}

function loadTrack(mp3Url) {
    audio.src = mp3Url;
    audio.load();

    // Extract name: "J. Cole - Track Name.mp3" -> "Track Name"
    const fileName = decodeURIComponent(mp3Url.split('/').pop());
    const cleanName = fileName.replace('.mp3', '').replace('J. Cole - ', '').trim();

    // Update the parent sidebar element
    const trackDisplay = document.getElementById('trackName');
    if (trackDisplay) {
        trackDisplay.textContent = cleanName;
    }

    // Handle turntable UI in parent
    const platter = document.getElementById('platterLabel');
    const playBtn = document.getElementById('playBtn');
    
    if (platter) platter.style.animationPlayState = 'running';
    if (playBtn) playBtn.innerHTML = "⏸";
    
    isPlaying = true;
    audio.play().catch(err => console.log("Playback error:", err));
}


function currentlyPlayingTrack(album, track) {
    // This happens in the current doc (the iframe)
    const items = document.querySelectorAll('.track-item');
    items.forEach(item => {
        if (item.textContent.includes(track)) {
            item.classList.add('playing');
        } else {
            item.classList.remove('playing');
        }
    });
}


const volumeSlider = document.getElementById('volumeSlider');
if (volumeSlider) {
    volumeSlider.value = audio.volume * 100;
    volumeSlider.oninput = (e) => { audio.volume = e.target.value / 100; };
}


function togglePlay() {
    if (audio.src === "" || audio.src.includes('null')) return;
    
    const platter = document.getElementById('platterLabel');
    const playBtn = document.getElementById('playBtn');

    if (isPlaying) {
        audio.pause();
        if(platter) platter.style.animationPlayState = 'paused';
        if(playBtn) playBtn.innerHTML = "▶";
    } else {
        audio.play();
        if(platter) platter.style.animationPlayState = 'running';
        if(playBtn) playBtn.innerHTML = "⏸";
    }
    isPlaying = !isPlaying;
}



function moveTrack(amount) {
    if (!selectedKey) return;
    const album = albums.find(a => a.key === selectedKey);
    const fileName = decodeURIComponent(audio.src.split('/').pop());
    const currentTrack = fileName.replace('.mp3', '').replace('J. Cole - ', '').trim();
    
    let currentIndex = album.tracks.findIndex(t => t.trim() === currentTrack);
    let nextIndex = (currentIndex + amount) % album.tracks.length;
    if (nextIndex < 0) nextIndex += album.tracks.length;

    const nextTrackName = album.tracks[nextIndex];
    const path = `../../assets/music/Cole/${album.title}/J. Cole - ${nextTrackName}.mp3`;
    
    currentlyPlayingTrack(album, nextTrackName);
    loadTrack(path);
}



window.addEventListener('load', () => {
    // Link Parent Buttons to Iframe Functions
    const pPlay = document.getElementById('playBtn');
    const pNext = document.getElementById('nextBtn');
    const pPrev = document.getElementById('prevBtn');
    const pClose = document.getElementById('closeBtn');

    if (pPlay) pPlay.onclick = togglePlay;
    if (pNext) pNext.onclick = () => moveTrack(1);
    if (pPrev) pPrev.onclick = () => moveTrack(-1);
    if (pClose) pClose.onclick = () => {
        audio.pause();
        audio.src = "";
        returnCard(true);
    };
});






